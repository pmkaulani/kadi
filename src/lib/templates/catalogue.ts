const TEMPLATE_ALIASES: Record<string, string> = {
  'a-place-to-call-home': 'first-home-botanical',
};

export function getTemplateById(id: string): TemplateDefinition | undefined {
  if (!id) return undefined;
  const direct = TEMPLATES.find((t) => t.id === id);
  if (direct) return direct;

  const aliasId = TEMPLATE_ALIASES[id];
  if (aliasId) {
    const aliasMatch = TEMPLATES.find((t) => t.id === aliasId);
    if (aliasMatch) return aliasMatch;
  }

  // Fallback: match by normalized title slug (e.g., 'a-place-to-call-home' -> 'A Place to Call Home')
  return TEMPLATES.find((t) => {
    const titleSlug = t.name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, '');
    return titleSlug === id;
  });
}

export function getTemplatesByCategory(category?: string): TemplateDefinition[] {
  if (!category || category === 'all') return TEMPLATES;
  return TEMPLATES.filter((t) => t.category === category);
}
